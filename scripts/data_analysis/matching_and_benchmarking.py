import numpy as np
import pandas as pd
from scipy.spatial.distance import cdist
from scipy.optimize import linear_sum_assignment
import sys



###SETUP & INPUTS###


# Inputs
groundtruth_detections_path = snakemake.input.groundtruth_detections
groundtruth_classes_path    = snakemake.input.groundtruth_classifications
detected_points_path        = snakemake.input.detected_points
classified_points_path      = snakemake.input.classified_points

# Outputs
class_benchmarks_outputpath  = snakemake.output.class_benchmarks
global_benchmarks_outputpath = snakemake.output.global_benchmarks

# Parameters
matching_threshold = snakemake.params.matching_threshold
sim_config         = snakemake.params.sim_settings

# Map the keys in config.yaml to the fixed IDs generated by data_simulation.py
CONFIG_KEY_TO_ID = {
    "stationary": 0,
    "aggregate":  1,
    "moving":     2
}

classes = []
class_names = {}

# Loop through the known keys to see what is active in the config
for key, class_id in CONFIG_KEY_TO_ID.items():
    # Check if section exists and is activated in the yaml
    if key in sim_config and sim_config[key].get("activate", False):
        classes.append(class_id)
        display_name = sim_config[key].get("display_name", key.title())
        class_names[class_id] = display_name

print(f"Benchmarking against active classes: {class_names}")


#only the target class (stationary = singular FRET pairs) counts as a correct detection
target_id = CONFIG_KEY_TO_ID["stationary"]
#without targets precision/recall/F1 mean nothing, so stop right away
if target_id not in classes:
    raise ValueError("The target class ('stationary') is not active in the config, so there is nothing to score")

def safe_div(n, d):
    return n / d if d > 0 else 0.0



###LOAD DATA AND SUBSET CHECK###


try:
    groundtruth_detections      = np.load(groundtruth_detections_path)
    groundtruth_classifications = np.load(groundtruth_classes_path)
    detected_points             = np.load(detected_points_path)
    classified_points           = np.load(classified_points_path)
except Exception as e:
    print(f"Error loading numpy arrays: {e}")
    sys.exit(1)

#if a selected point is not one of the detected points, that algorithm's wrapper has a bug, so stop here
#the file path shows which algorithm
if len(classified_points) > 0:
    if len(detected_points) == 0:
        raise ValueError(f"Selected points found, but no detected points in {classified_points_path}, check that algorithm's wrapper")  #selected points but no detections at all

    #for every selected point: distance to the closest detected point (0 if it is one of them)
    distance_to_closest_detection = cdist(classified_points, detected_points).min(axis=1)
    if np.any(distance_to_closest_detection > 1e-9):  #1e-9 instead of exactly 0, to allow for rounding
        raise ValueError(f"Selection is not a subset of the detections in {classified_points_path}, check that algorithm's wrapper")



###MATCHING LOGIC###



def matching(points_gt, points_det, max_dist):

    # Handle empty inputs gracefully
    if len(points_gt) == 0:
        return [], [], list(range(len(points_det)))
    if len(points_det) == 0:
        return [], list(range(len(points_gt))), []

    #Euclidean distance matrix between GT and Detected points Shape: (n_gt, n_det)
    cost_matrix = cdist(points_gt, points_det)
    # distances > max_dist to a penalty value larger than any possible valid match.
    penalty_value = 1e6 
    cost_matrix[cost_matrix > max_dist] = penalty_value
    #Finding lowest sum of row and col indices. lowest cost matching, very strongly punishing matches that exceed max_dist
    row_ind, col_ind = linear_sum_assignment(cost_matrix) #function named after the problem and not the solution (hungarian) weird
    #Removing matches that exceed max_dist
    matched_pairs = []

    matched_gt = np.zeros(len(points_gt), dtype=bool)    #Made true, then this ground-truth point has a match
    matched_det = np.zeros(len(points_det), dtype=bool)  #Made true, then this detection has a match

    for i in range(len(row_ind)):
        r = row_ind[i]
        c = col_ind[i]
        dist = cost_matrix[r, c]

        #Matched?
        if dist <= max_dist:
            matched_pairs.append((r, c))
            matched_gt[r] = True
            matched_det[c] = True

    #flatnonzero: indices of true
    unmatched_gt = np.flatnonzero(~matched_gt)    # missed ground-truth points
    unmatched_det = np.flatnonzero(~matched_det)  # detections without a match
            
    return matched_pairs, unmatched_gt, unmatched_det



###MATCHING & BENCHMARKING###



def classes_of_matches(points):
    pairs, ___, unmatched_det = matching(groundtruth_detections, points, matching_threshold)

    matched_classes = []
    for groundtruth_index, _ in pairs:
        matched_classes.append(groundtruth_classifications[groundtruth_index])
    matched_classes = np.array(matched_classes)

    return matched_classes, unmatched_det
#matched_classes = [0, 0, 1, 0, 2, ...]
#unmatched_det = [3, 5, 7, ...] indices of points that matched nothing

#detections (before selection) and selections (after selection) are matched separately because wrapperse dont output indices
classes_detected, noise_detected = classes_of_matches(detected_points)
classes_selected, noise_selected = classes_of_matches(classified_points)



###CALCULATE METRICS###



#PER CLASS: how many of each class were found, before (raw) and after (filtered) selection, here is matched classes used
rows = []
for class_id in classes:
    n_in_groundtruth = np.sum(groundtruth_classifications == class_id)  #how many exist in the ground truth
    n_detected = np.sum(classes_detected == class_id)               #how many were detected
    n_selected = np.sum(classes_selected == class_id)             #how many are left after selection

    rows.append({
        "Class": class_names[class_id],
        "Raw_Count": n_detected,
        "Filtered_Count": n_selected,
        "Retention": safe_div(n_selected, n_detected),
        "Recall_Raw": safe_div(n_detected, n_in_groundtruth),
        "Recall_Filtered": safe_div(n_selected, n_in_groundtruth)
    })

#NOISE: detections that matched no ground-truth point at all, here is unmatched used
rows.append({
    "Class": "Pure Noise",
    "Raw_Count": len(noise_detected),
    "Filtered_Count": len(noise_selected),
    "Retention": safe_div(len(noise_selected), len(noise_detected)),
    "Recall_Raw": 0.0,
    "Recall_Filtered": 0.0
})

df_classes = pd.DataFrame(rows)

#GLOBAL: precision/recall/F1 for the target class (target_id, set at the top)
n_targets = np.sum(groundtruth_classifications == target_id)
targets_detected = np.sum(classes_detected == target_id) 
targets_selected = np.sum(classes_selected == target_id) 
recall_detection = safe_div(targets_detected, n_targets)
recall_selection = safe_div(targets_selected, n_targets)

#precision: fraction of ALL detections/selections that are targets (so aggregates and mobiles count as wrong too, for better comparison of det and sel in rp plot (same metric))
precision_detection = safe_div(targets_detected, len(detected_points))
precision_selection = safe_div(targets_selected, len(classified_points))

#F1: harmonic mean of precision and recall (harmonic makes a strong punishment for lower numbers)
f1_detection = safe_div(2 * (precision_detection * recall_detection), (precision_detection + recall_detection))
f1_selection = safe_div(2 * (precision_selection * recall_selection), (precision_selection + recall_selection))

df_global = pd.DataFrame({
    "Raw": [precision_detection, recall_detection, f1_detection],
    "Filtered": [precision_selection, recall_selection, f1_selection]
}, index=["Global_Precision", "Global_Recall", "Global_F1_Score"])


###SAVE OUTPUTS###


df_classes.to_csv(class_benchmarks_outputpath, index=False) 
df_global.to_csv(global_benchmarks_outputpath)

print(f"Benchmarking complete. Saved to results folder.")